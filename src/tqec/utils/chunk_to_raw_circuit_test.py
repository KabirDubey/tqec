    def test_circuit_equivalence_analysis(self):
        """Analyze circuit equivalence between gen and fixed_bulk approaches."""
        distance = 3
        patch = gen.surface_code_patch(distance=distance)
        chunk = gen.standard_surface_code_chunk(patch)
        
        # Extract circuit structure details
        circuit = chunk.circuit
        
        # Analyze instruction types
        instruction_types = {}
        for inst in circuit:
            if isinstance(inst, stim.CircuitRepeatBlock):
                instruction_types['REPEAT'] = instruction_types.get('REPEAT', 0) + 1
            else:
                instruction_types[inst.name] = instruction_types.get(inst.name, 0) + 1
        
        # Surface code should have typical gate set
        expected_gates = {'H', 'CX', 'M', 'R'}  # Typical surface code gates
        found_gates = set(instruction_types.keys()) & expected_gates
        assert len(found_gates) > 0, f"Should find some expected gates, found: {instruction_types}"
        
        # Gen circuits have measurements that can be processed into detectors by TQEC
        measurements = instruction_types.get('M', 0) + instruction_types.get('MX', 0)
        assert measurements > 0, "Should have measurements"
        assert instruction_types.get('CX', 0) > 0, "Should have CX gates"

        # Convert gen circuit through our converter
        layer = chunk_to_raw_circuit(chunk)
        converted_circuit = layer.circuit_factory(1).get_circuit()
        
        # The converted circuit should maintain the same structure
        converted_instructions = {}
        for inst in converted_circuit:
            converted_instructions[inst.name] = converted_instructions.get(inst.name, 0) + 1
        
        # Key measurements and gates should be preserved
        converted_measurements = converted_instructions.get('M', 0) + converted_instructions.get('MX', 0)
        assert converted_measurements == measurements, "Measurements should be preserved in conversion"
        assert converted_instructions.get('CX', 0) == instruction_types.get('CX', 0), "CX gates should be preserved"

    def test_qubit_coordinate_consistency(self):
        """Test that qubit coordinates are handled consistently."""
        patch = gen.surface_code_patch(distance=3)
        chunk = gen.standard_surface_code_chunk(patch)
        
        # Analyze coordinate patterns in chunk
        coords = list(chunk.q2i.keys())
        
        # Should have both data qubits (integer coords) and measure qubits (half-integer)
        integer_coords = [q for q in coords if q.real % 1 == 0 and q.imag % 1 == 0]
        half_integer_coords = [q for q in coords if q.real % 1 == 0.5 or q.imag % 1 == 0.5]
        
        assert len(integer_coords) > 0, "Should have data qubits at integer coordinates"
        assert len(half_integer_coords) > 0, "Should have measure qubits at half-integer coordinates"
        
        # Test that our shape extraction handles this correctly
        layer = chunk_to_raw_circuit(chunk)
        shape = layer.scalable_raw_shape
        
        # Shape should encompass all coordinates
        min_real = min(q.real for q in coords)
        max_real = max(q.real for q in coords)
        min_imag = min(q.imag for q in coords)
        max_imag = max(q.imag for q in coords)
        
        expected_width = int(max_real - min_real) + 1
        expected_height = int(max_imag - min_imag) + 1
        
        assert shape.x(1) == expected_width
        assert shape.y(1) == expected_height


