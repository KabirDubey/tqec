    def test_surface_code_memory_comparison(self, fixed_bulk_builder):
        """Compare surface code memory circuits from both systems."""
        from tqec.compile.specs.base import CubeSpec
        from tqec.computation.cube import ZXCube
        from tqec.utils.enums import Basis
        
        # Generate circuit using gen system
        distance = 3
        patch = gen.surface_code_patch(distance=distance)
        gen_chunk = gen.standard_surface_code_chunk(patch)
        gen_layer = chunk_to_raw_circuit(gen_chunk)
        gen_circuit = gen_layer.circuit_factory(1).get_circuit()
        
        # Generate circuit using fixed_bulk system  
        spec = CubeSpec(kind=ZXCube(x=Basis.Z, y=Basis.X, z=Basis.Z))  # Memory cube
        fixed_bulk_block = fixed_bulk_builder(spec)
        
        # Compare basic properties
        assert len(gen_circuit) > 0
        assert len(fixed_bulk_block.layer_sequence) > 0
        
        # Both should produce valid circuits with measurements
        gen_measurements = sum(1 for inst in gen_circuit if inst.name.startswith('M'))
        gen_gates = sum(1 for inst in gen_circuit if inst.name in ['CX', 'H', 'S', 'R', 'RX'])
        
        assert gen_measurements > 0, "Gen circuit should have measurements"
        assert gen_gates > 0, "Gen circuit should have quantum gates"

    def test_chunk_vs_plaquette_layer_structure(self):
        """Compare the structural differences between chunk and plaquette approaches."""
        # Gen approach: single chunk -> single RawCircuitLayer
        patch = gen.surface_code_patch(distance=3)
        chunk = gen.standard_surface_code_chunk(patch)
        gen_layer = chunk_to_raw_circuit(chunk)
        
        # Verify gen layer properties
        assert gen_layer.scalable_raw_shape.x(1) > 0
        assert gen_layer.scalable_raw_shape.y(1) > 0
        assert gen_layer.scalable_num_moments(1) > 0
        
        # Fixed_bulk approach uses PlaquetteLayers - this is fundamentally different
        # but we can verify that our chunk conversion produces a valid layer
        from tqec.compile.blocks.block import Block
        gen_block = Block([gen_layer])
        
        assert len(gen_block.layer_sequence) == 1
        assert gen_block.layer_sequence[0] is gen_layer

    def test_detector_and_observable_handling(self):
        """Compare how detectors and observables are handled in both systems."""
        # Test with observable
        patch = gen.surface_code_patch(distance=3)
        obs = gen.PauliString({0: 'Z', 1: 'Z', 2: 'Z'})  # Simple observable
        chunk_with_obs = gen.standard_surface_code_chunk(patch, obs=obs)
        
        layer = chunk_to_raw_circuit(chunk_with_obs)
        circuit = layer.circuit_factory(1).get_circuit()
        
        # Gen circuits contain measurements but may not have explicit detectors/observables
        # This is normal - they are generated at higher levels of the compilation
        measurements = sum(1 for inst in circuit if inst.name.startswith('M'))
        gates = sum(1 for inst in circuit if inst.name in ['CX', 'H', 'S', 'R', 'RX'])
        
        assert measurements > 0, "Should have measurements"
        assert gates > 0, "Should have quantum gates"
        
        # Verify the observable is preserved in the chunk data
        # The observable information is typically stored in the chunk metadata
        
        # Now let's demonstrate detector computation comparison
        detector_comparison = self._compare_detector_generation(chunk_with_obs, layer)
        
        # Both circuits should generate the same number of detectors when processed by TQEC
        assert detector_comparison['raw_generated_detectors'] == detector_comparison['tqec_detectors'], \
            f"TQEC detector generation should produce same results: raw={detector_comparison['raw_generated_detectors']}, tqec={detector_comparison['tqec_detectors']}"

    def _compare_detector_generation(self, chunk: gen.Chunk, layer):
        """Compare detector generation between raw gen circuit and TQEC processing."""
        from tqecd import annotate_detectors_automatically
        
        # Get the raw gen circuit
        raw_circuit = chunk.circuit
        raw_measurements = sum(1 for inst in raw_circuit if inst.name.startswith('M'))
        raw_detectors = sum(1 for inst in raw_circuit if inst.name == 'DETECTOR')
        
        # Get the TQEC-processed circuit 
        tqec_circuit = layer.circuit_factory(1).get_circuit()
        tqec_measurements = sum(1 for inst in tqec_circuit if inst.name.startswith('M'))
        
        # Use TQEC's automatic detector annotation on both circuits
        try:
            # Apply TQEC's detector generation to both circuits
            raw_with_detectors = annotate_detectors_automatically(raw_circuit)
            tqec_with_detectors = annotate_detectors_automatically(tqec_circuit)
            
            # Count detectors in the annotated circuits
            raw_generated_detectors = sum(1 for inst in raw_with_detectors if inst.name == 'DETECTOR')
            tqec_generated_detectors = sum(1 for inst in tqec_with_detectors if inst.name == 'DETECTOR')
                
        except Exception as e:
            # Fallback if detector generation fails
            raw_generated_detectors = raw_detectors
            tqec_generated_detectors = 0
        
        return {
            'raw_measurements': raw_measurements,
            'tqec_measurements': tqec_measurements,
            'raw_detectors': raw_detectors,
            'tqec_detectors': tqec_generated_detectors,
            'raw_generated_detectors': raw_generated_detectors
        }

