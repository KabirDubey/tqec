class TestShapeExtraction:
    """Test shape extraction from chunk coordinates."""

    def test_extract_shape_empty_chunk(self):
        """Test shape extraction from empty chunk."""
        chunk = gen.Chunk(stim.Circuit(), {}, [])
        shape = extract_shape_from_chunk(chunk)
        
        assert shape.x(1) == 1
        assert shape.y(1) == 1

    def test_extract_shape_single_qubit(self):
        """Test shape extraction from single qubit."""
        chunk = gen.Chunk(stim.Circuit("H 0"), {0+0j: 0}, [])
        shape = extract_shape_from_chunk(chunk)
        
        assert shape.x(1) == 1
        assert shape.y(1) == 1

    def test_extract_shape_surface_code_like(self):
        """Test shape extraction from surface code-like coordinates."""
        # Simulate a 3x3 surface code grid with data qubits at integer coordinates
        # and measurement qubits at half-integer coordinates
        q2i = {}
        qubit_index = 0
        
        # Data qubits: 3x3 grid
        for x in range(3):
            for y in range(3):
                q2i[complex(x, y)] = qubit_index
                qubit_index += 1
        
        # Measurement qubits: offset by 0.5 + 0.5j
        for x in range(2):
            for y in range(2):
                q2i[complex(x + 0.5, y + 0.5)] = qubit_index
                qubit_index += 1
        
        chunk = gen.Chunk(stim.Circuit("H 0"), q2i, [])
        shape = extract_shape_from_chunk(chunk)
        
        # Should span from 0 to 2.5, so width/height = 3
        assert shape.x(1) == 3
        assert shape.y(1) == 3


