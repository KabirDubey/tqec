class TestGenVsFixedBulkComparison:
    """Compare circuits generated by gen vs fixed_bulk systems."""

    @pytest.fixture
    def css_compiler(self):
        """CSS plaquette compiler for fixed_bulk system."""
        from tqec.plaquette.compilation.css import CSSPlaquetteCompiler
        return CSSPlaquetteCompiler

    @pytest.fixture  
    def fixed_bulk_builder(self, css_compiler):
        """Fixed bulk cube builder."""
